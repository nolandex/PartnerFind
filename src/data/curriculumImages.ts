/**
 * Helper to get a curated image for a class, module, and video index.
 */
export function getLessonImage(classIdx: number, moduleIdx: number, videoIdx: number): string {
  const cls = CURRICULUM_IMAGES[classIdx % CURRICULUM_IMAGES.length];
  if (!cls) return "https://images.unsplash.com/photo-1516321318423-f06f85e504b3?auto=format&fit=crop&w=640&q=80";
  const mod = cls[moduleIdx % cls.length];
  if (!mod) return "https://images.unsplash.com/photo-1516321318423-f06f85e504b3?auto=format&fit=crop&w=640&q=80";
  return mod[videoIdx % mod.length] || "https://images.unsplash.com/photo-1516321318423-f06f85e504b3?auto=format&fit=crop&w=640&q=80";
}
